SANS_GAP = 1        # blank columns between glyphs (real sign: 2 after digits; compressed, see report)
SANS_SPACE_ADV = 2  # space advance; with the 1-col gap of the previous glyph = 3 blank columns
DIGIT_ADV = 7       # tabular digits: 6 wide + 1 gap (real sign: 8)


def sans_glyphs():
    """-> {ch: (rows, xo, yo, adv)} with yo relative to the baseline (row 9 is the last row above it)."""
    out = {}
    for ch, (rows, xo) in T.items():
        w = len(rows[0])
        adv = DIGIT_ADV if ch.isdigit() else xo + w + SANS_GAP
        out[ch] = (rows, xo, -10, adv)
    out[' '] = ([], 0, 0, SANS_SPACE_ADV)
    return out


# ============================================================================
# Bold fonts rasterised from Liberation Sans Bold
# ============================================================================
SS = 16  # supersampling factor
CAP_EM = 1409 / 2048  # Liberation Sans cap height / em


def raster_bold(ttf, ch, cap, sx=1.0, thr=0.6):
    """Render one glyph with box-filter supersampling; choose the sub-pixel x phase that gives the
    crispest strokes. Baseline is aligned with an LED row boundary. Returns (rows, xo, yo, adv)."""
    from PIL import Image, ImageDraw, ImageFont
    f = ImageFont.truetype(ttf, int(round(cap / CAP_EM * SS)))
    asc, desc = f.getmetrics()
    adv_ss = f.getlength(ch)
    pad = 3 * SS
    W = int(adv_ss) + 2 * pad
    H = asc + desc + 2 * SS
    best = None
    for phase in range(0, SS, 2):
        im = Image.new("L", (W + SS, H), 0)
        ImageDraw.Draw(im).text((pad + phase, SS), ch, font=f, fill=255)
        base = SS + asc                               # baseline y in supersampled pixels
        top = base - ((base // SS) * SS)              # crop so base falls on a cell boundary
        im = im.crop((0, top, im.width, top + ((im.height - top) // SS) * SS))
        im = im.resize((int(im.width * sx) // SS, im.height // SS), Image.BOX)
        px = im.load()
        cov = [[px[x, y] / 255 for x in range(im.width)] for y in range(im.height)]
        crisp = sum(abs(c - 0.5) for row in cov for c in row)
        if best is None or crisp > best[0]:
            best = (crisp, cov, (pad + phase) * sx / SS, (base - top) // SS)
    _, cov, pen_x, base_row = best
    bits = [[c >= thr for c in row] for row in cov]
    ys = [y for y, row in enumerate(bits) if any(row)]
    xs = [x for row in bits for x, b in enumerate(row) if b]
    adv = int(round(adv_ss * sx / SS))
    if not xs:
        return [], 0, 0, adv
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    rows = ["".join("#" if bits[y][x] else "." for x in range(x0, x1 + 1)) for y in range(y0, y1 + 1)]
    xo = x0 - int(round(pen_x))
    return rows, xo, y0 - base_row, adv



def t(ch, *rows, xo=0):
    w = len(rows[0])
    assert all(len(r) == w for r in rows), ch
    assert len(rows) in (10, 11, 12), (ch, len(rows))
    T[ch] = (list(rows), xo)


def lc(ch, xrows, asc=None, desc=(), xo=0):
    """Lower case: xrows = x-height rows 3..9; asc = rows 0..2 (ascender), desc = rows 10..11."""
    w = len(xrows[0])
    asc = list(asc) if asc else ["." * w] * 3
    t(ch, *(asc + list(xrows) + list(desc)), xo=xo)



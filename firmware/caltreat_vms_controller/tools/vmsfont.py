def bold_glyphs(ttf, cap, chars, sx=1.0, thr=0.6, tracking=0):
    out = {}
    for ch in chars:
        rows, xo, yo, adv = raster_bold(ttf, ch, cap, sx, thr)
        out[ch] = (rows, xo, yo, max(1, adv + tracking))
    return out


